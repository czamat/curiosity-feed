const PRIORITY: Record<FeedCategory, number> = {
  philosophy: 0,
  physics: 1,
  math: 2,
  psychology: 3,
  misc: 4,
};

function scoreHaystack(hay: string, cat: FeedCategory): number {
  let t = 0;
  for (const kw of KW[cat]) {
    if (hay.includes(kw)) t += kw.includes(' ') ? 4 : 2;
  }
  return t;
}

/** Pick the best-matching feed category; weak matches fall through to `misc`. */
export function bestCategory(quote: { text: string; from: string }): FeedCategory {
  const hay = `${quote.text} ${quote.from}`.toLowerCase();
  const scored = FEED_CATEGORIES.map((c) => [c, scoreHaystack(hay, c)] as const);
  let bestScore = -1;
  for (const [, s] of scored) {
    if (s > bestScore) bestScore = s;
  }
  if (bestScore < 2) return 'misc';
  const winners = scored.filter(([, s]) => s === bestScore);
  if (winners.length === 1) return winners[0]![0];
  return winners
    .map(([c]) => c)
    .sort((a, b) => PRIORITY[a] - PRIORITY[b])[0]!;
}

export function scoreFor(quote: { text: string; from: string }, cat: FeedCategory): number {
  const hay = `${quote.text} ${quote.from}`.toLowerCase();
  return scoreHaystack(hay, cat);
}
