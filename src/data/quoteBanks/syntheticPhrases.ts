const SYN_ATTRIBUTION = 'Curiosity (original aphorism)';

export function syntheticRow(cat: FeedCategory, k: number): QuoteRow {
  const a = k % 20;
  const b = Math.floor(k / 20) % 20;
  const c = Math.floor(k / 400) % 20;
  const set = BY_CAT[cat];
  const text = `${set.openers[a]} ${set.mids[b]}; ${set.ends[c]}.`;
  return {
    text,
    attribution: SYN_ATTRIBUTION,
    explanation: `An original, compact aphorism written to expand variety in the ${set.label} track. It is not a claim about a specific historical source — it is a stylistic “wise line” that fits the category’s themes, plus honest metadata so the feed can stay large without pretending every line is a museum quote.`,
    eli5: 'The app added a new short line here on purpose, so the same few famous quotes do not show up as often as before.',
  };
}
